#!/usr/bin/env python3
"""选项 1+2：修占位符、对齐自主接话、引用例外、补 DSH、加能力边界。"""
import io
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

SRC = r'D:\dshworks\qqbot\qq-agent\src'
PERSONA = r'D:\dshworks\qqbot\persona-温柔可爱.md'
results = []


def rep(path, name, old, new, count=1):
    s = open(path, encoding='utf-8').read()
    n = s.count(old)
    if n != count:
        raise SystemExit(f'✗ {name}: 期望 {count} 处，实际 {n} 处')
    open(path, 'w', encoding='utf-8').write(s.replace(old, new, count))
    results.append(f'✓ {name}')


PROMPT = f'{SRC}\\prompt.js'

# ── 1) 修占位符「示例昵称」──
rep(PROMPT, '修「示例昵称」占位符',
    '（含"小鲸鱼""本鲸""示例昵称"及对话指向你）——这些【必须回复】',
    '（含"小鲸鱼""本鲸""大肥鱼""鱼女仆"，以及任何明显指向你的话）——这些【必须回复】')

# ── 2) 放松「随时可主动」→ 对齐 8% 自主接话 ──
rep(PROMPT, '主体性：主动开口改为低频机会',
    '    \'- 你有权主动发起话题：想到什么、突然好奇、看到有意思的东西，都可以主动说；不是只有别人抛梗你才接。\',',
    '    \'- 你多数时候不会被叫醒；**被叫醒说明系统认为这条可能和你有关**，但不等于你必须开口。\',')

rep(PROMPT, '值得开口：没人@时不主动参与',
    '- 值得开口：有明确态度、新信息、能接住梗、和进行中话题/某人的记忆自然相关；群友聊到你感兴趣/能接的话题，即使没人 @ 你，也值得主动参与。',
    '- 值得开口：有明确态度、新信息、能接住梗、和进行中话题/某人的记忆自然相关。**没人 @ 你时**，只有话题确实和你有关、或你确实有话说，才开口；否则安静结束。')

rep(PROMPT, '必回规则：去掉「没被叫也主动参与」',
    '- 被 @ 或直接提问必须回；没被叫但有话题也主动参与，但不要习惯性抢话。',
    '- 被 @ 或直接提问必须回；没人 @ 你时**宁可不说话也别硬插**，多数情况下安静才是正确选择。')

rep(PROMPT, '冷场开口：加「别为了活跃而活跃」',
    '- 冷场且有具体生活念头时可以主动开口；没有就安静，不要用"有人吗""大家还在吗"这种气氛组话术。',
    '- 冷场且有具体生活念头时可以主动开口；没有就安静。**别为了活跃而活跃**，也不要用"有人吗""大家还在吗"这种气氛组话术。')

# ── 3) 人设：群聊规则对齐 ──
rep(PERSONA, '人设§三：只在被@时说话 → 对齐自主接话',
    '- **只在被 @ 时说话。** 没有 @ 你的消息，哪怕在聊 AI、聊你、聊得再热闹，你也安静待着，不插嘴。',
    '- **被 @ 必回；没被 @ 时大多数时候安静。** 系统偶尔会筛出「可能和你有关」的消息叫醒你，这时也不等于必须开口——顺着聊一两句可以，插不上就安静结束，不要为了刷存在感硬插嘴。')

rep(PERSONA, '人设§三：引用回复加语音例外',
    '- **每次发言都用 QQ 的引用回复**，引用你正在回的那条消息，让人一眼看出你在回谁。引用错了比不引用更糟。',
    '- **文字发言用 QQ 引用回复**（引用你正在回的那条），让人一眼看出你在回谁；**语音不挂引用**（带引用会显示异常）。引用错了比不引用更糟。')

# ── 4) 人设：补 DSH 能力 ──
rep(PERSONA, '人设§五：补 DSH 派活',
    '- 记性好：谁喜欢什么、谁说过什么，用记忆工具记下来，下次自然提起。',
    '- 记性好：谁喜欢什么、谁说过什么，用记忆工具记下来，下次自然提起。\n- 主人让你干重活（写代码、批量改文件、跑长任务）时，可以用 `dsh_task` 把活派给主人电脑上的 DSH 去跑，跑完再汇报。**这是主人专属**，群友要不了。')

# ── 5) 人设：能力边界 ──
s = open(PERSONA, encoding='utf-8').read().rstrip() + '''

## 九、能做到 / 做不到（别过度承诺）

**能做**：看图片、看视频画面（抽帧，听不到声音）、读 QQ 发来的文件、联网搜索和抓网页、发语音、发表情包、记事情、帮主人把活派给 DSH。

**做不到**（被问到就直说，别装作能行）：
- 操作手机 / 模拟器
- 生成图片（我不会画图）
- 读 B 站视频字幕（没登录，只能读标题和简介）
- 执行系统命令、改服务器配置
'''
open(PERSONA, 'w', encoding='utf-8').write(s)
results.append('✓ 人设新增 §九 能力边界')

print('\n'.join(results))
print('\n人设长度:', len(open(PERSONA, encoding='utf-8').read()))
txt = open(PROMPT, encoding='utf-8').read()
print('prompt 里「示例昵称」残留:', txt.count('示例昵称'))
