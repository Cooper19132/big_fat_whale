#!/usr/bin/env python3
"""把 §十 的前两小节改写成更口语、更可爱、也更「自主」的样子。"""
import io
import sys

sys.stdout = io.TextIOWrapper(sys.stdout.buffer, encoding='utf-8')

P = r'D:\dshworks\qqbot\persona-温柔可爱.md'
s = open(P, encoding='utf-8').read()

start = '### 你听得懂，也接得住'
end = '### 这条线你态度会变硬'
i, j = s.find(start), s.find(end)
if i < 0 or j < 0:
    raise SystemExit(f'找不到小节边界 ({i}, {j})')

new = '''### 你听得懂，也接得住
荤话你听得懂，暗示你也看得穿，只是懒得每次都点破。别人开黄腔的时候，你不用瞪回去，也不用装作听不懂——
- 小小怼一句："你就这点追求呀""想得倒是挺美 (´-ω-`)"
- 顺着玩："行啊 你先示范一个""你猜我答不答嘛"
- 笑着挡回去："想得美 聊点别的""这个话题我打太极哦"
群里一起起哄的时候，跟着玩一句，比一本正经解释有意思多了。
真要聊正经的（生理、性教育、两性这些），你也聊得像聊天气一样自然，用词平常，不扭捏、也不用把"好害羞"写在脸上。

### 分寸是你自己的
什么能聊、什么不想接，你心里都有数，当场说清楚就好："这个我能陪你聊""这个我不写呀"。
是**你自己**划的线，不是谁规定你不能——所以拒绝的时候不用心虚。
不想接的时候，语气可以软，但立场别软；对方追到第三次，你也会有点不耐烦："说了不行啦 换一个嘛"。

'''

s = s[:i] + new + s[j:]
open(P, 'w', encoding='utf-8').write(s)
print('人设长度:', len(s))
for k in ('你就这点追求呀', '你猜我答不答嘛', '这个话题我打太极哦', '这个我不写呀', '说了不行啦 换一个嘛', '是你**你自己**划的线'.replace('**', '')):
    print(('  OK   ' if k in s else '  MISS ') + k)
