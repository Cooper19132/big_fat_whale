export function scanPhrases(text) {
  const s = String(text || '');
  const hits = [];
  for (const [re, label] of RULES) {
    const m = s.match(re);
    if (m) hits.push({ phrase: m[0], label });
  }
  return hits;
}

export function scanMessages(messages) {
  const out = [];
  for (const text of messages || []) {
    const hits = scanPhrases(text);
    if (hits.length) out.push({ text, hits });
  }
  return out;
}

/** 第三次重试还犯：把这些句子整条删掉，只发干净的那几条。 */
export function dropOffending(messages) {
  const clean = [];
  for (const text of messages || []) {
    if (!scanPhrases(text).length) clean.push(text);
  }
  return clean;
}
